// Themed 3D models: fixed "core" parts (not removable) + anchors (flat surfaces where screwed parts attach).
// Anchor: p = centre on the surface, r = euler so local +z is the outward normal, w/h = usable size.
// back:true anchors face away from the start camera (used only from level 15).  special:true = a shaped part (ear, fin, hubcap...) always added from level 4.
const H = Math.PI/2;
function face(id, c, s, f, o={}){ // anchor on face f of a box centred c with size s
  const [x,y,z]=c, [w,h,d]=s, m=0.12;
  const A = { F:{p:[x,y,z+d/2],r:[0,0,0],w,h}, B:{p:[x,y,z-d/2],r:[0,Math.PI,0],w,h,back:true},
    R:{p:[x+w/2,y,z],r:[0,H,0],w:d,h}, L:{p:[x-w/2,y,z],r:[0,-H,0],w:d,h},
    T:{p:[x,y+h/2,z],r:[-H,0,0],w,h:d}, D:{p:[x,y-h/2,z],r:[H,0,0],w,h:d,back:true} }[f];
  const a = { id, ...A, ...o }; a.w=(o.w??A.w)-m; a.h=(o.h??A.h)-m;
  if (o.dx||o.dy){ a.p=a.p.slice(); } // offsets applied in local frame by game; kept simple: use o.p to override
  return a;
}
const sp = (id,p,r,w,h,shape,o={}) => ({ id,p,r,w,h,shape,special:true,...o });

